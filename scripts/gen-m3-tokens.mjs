// Sinh vai trò màu Material 3 cho design system Hệ thống X từ seed (sao từ livesstream-ai-fe).
//   node scripts/gen-m3-tokens.mjs  → src/design/tokens.css + src/design/tokens.generated.json
// Uses Google's material-color-utilities (HCT, DynamicScheme), the same engine as Material Theme Builder.
import { writeFileSync } from "node:fs";
import {
  argbFromHex,
  hexFromArgb,
  Hct,
  MaterialDynamicColors as M,
  SchemeFidelity,
  customColor,
} from "@material/material-color-utilities";

const SEED = "#4F46E5"; // indigo, cùng seed với docs/design-system/tokens.json
// E-commerce roles on top of M3: each becomes color / on-color / color-container / on-color-container,
// harmonised toward the seed so they sit in the same palette.
const CUSTOM = [
  { name: "success", value: "#2E7D32", blend: true, usage: "Ready, connected, paid, active package." },
  { name: "warning", value: "#B26A00", blend: false, usage: "Expiring soon, needs review, retrying." },
  {
    name: "live",
    value: "#E0213F",
    blend: false,
    usage: "Recording (REC) indicator only. Never for errors.",
  },
  { name: "price", value: "#C2410C", blend: false, usage: "Unused in Hệ thống X; kept for compatibility." },
];

const ROLES = [
  "primary",
  "onPrimary",
  "primaryContainer",
  "onPrimaryContainer",
  "secondary",
  "onSecondary",
  "secondaryContainer",
  "onSecondaryContainer",
  "tertiary",
  "onTertiary",
  "tertiaryContainer",
  "onTertiaryContainer",
  "error",
  "onError",
  "errorContainer",
  "onErrorContainer",
  "surface",
  "onSurface",
  "onSurfaceVariant",
  "surfaceDim",
  "surfaceBright",
  "surfaceContainerLowest",
  "surfaceContainerLow",
  "surfaceContainer",
  "surfaceContainerHigh",
  "surfaceContainerHighest",
  "outline",
  "outlineVariant",
  "inverseSurface",
  "inverseOnSurface",
  "inversePrimary",
  "scrim",
  "shadow",
];
const kebab = (s) => s.replace(/[A-Z]/g, (c) => "-" + c.toLowerCase());

const seed = argbFromHex(SEED);
const schemes = {
  light: new SchemeFidelity(Hct.fromInt(seed), false, 0),
  dark: new SchemeFidelity(Hct.fromInt(seed), true, 0),
};
const out = { light: {}, dark: {} };
for (const mode of ["light", "dark"]) {
  for (const r of ROLES) out[mode][kebab(r)] = hexFromArgb(M[r].getArgb(schemes[mode]));
  for (const c of CUSTOM) {
    const g = customColor(seed, { name: c.name, value: argbFromHex(c.value), blend: c.blend })[mode];
    out[mode][c.name] = hexFromArgb(g.color);
    out[mode][`on-${c.name}`] = hexFromArgb(g.onColor);
    out[mode][`${c.name}-container`] = hexFromArgb(g.colorContainer);
    out[mode][`on-${c.name}-container`] = hexFromArgb(g.onColorContainer);
  }
}

const block = (vars) =>
  Object.entries(vars)
    .map(([k, v]) => `  --md-sys-color-${k}: ${v};`)
    .join("\n");
writeFileSync(
  "src/design/tokens.css",
  `/* GENERATED by scripts/gen-m3-tokens.mjs from seed ${SEED} — do not edit by hand. */
:root {
${block(out.light)}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${block(out.dark).replace(/^/gm, "  ")}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${block(out.dark)}
  color-scheme: dark;
}
`,
);
writeFileSync(
  "src/design/tokens.generated.json",
  JSON.stringify({ seed: SEED, custom: CUSTOM, ...out }, null, 2),
);
console.log(Object.keys(out.light).length, "roles", out.light.primary, out.dark.primary);
